import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Observer} from 'astronomy-engine';
import {observingSky, moonEvents, skyPoint, horizontal, validateObserver} from '../outputs/observing-test.mjs';
import {starObject} from '../lib/astro/data.ts';
import {readCatalog, discover, updateDiscovery} from '../lib/astro/catalog.ts';
const data={stars:JSON.parse(readFileSync('public/data/stars-3d.json','utf8')),sky:[],lines:[],constellations:[]};
const date=new Date('2026-09-07T03:00:00Z');
const polaris=data.stars.find(s=>s.name==='Polaris');
assert.ok(polaris);
const north=horizontal(starObject(polaris),new Observer(40,-75,0),date);
assert.ok(Math.abs(north.altitude-40)<1.5,'Polaris should be close to observer latitude');
const south=horizontal(starObject(polaris),new Observer(-34,151,0),date);
assert.ok(south.altitude < -32,'Polaris must be below a southern observer horizon');
assert.ok(skyPoint(0,90).x < 230,'East must appear left on overhead chart');
assert.equal(skyPoint(90,180).y,230);
const polar=observingSky(data,89,0,new Date('2026-06-21T12:00:00Z'));
assert.equal(polar.sunset,null,'Polar day must not invent a sunset');
assert.ok(polar.sunAltitude>0);
assert.throws(()=>validateObserver(91,0,date));
assert.throws(()=>validateObserver(0,181,date));
assert.throws(()=>validateObserver(0,0,new Date('invalid')));
// Independent reference: NASA/GSFC, https://eclipse.gsfc.nasa.gov/phase/phase2001gmt.html
const phases=moonEvents(new Date('2024-04-08T00:00:00Z'));
assert.equal(phases[0].name,'New Moon');
assert.ok(Math.abs(phases[0].date-new Date('2024-04-08T18:21:00Z'))<120000,'New Moon must agree with NASA table within two minutes');
assert.equal(phases.length,6);
assert.ok(phases.every((p,i)=>!i||p.date>phases[i-1].date));
const memory=new Map([['astroguide.guest-catalog.v1',JSON.stringify([{id:'earth',name:'Earth',type:'Planet',viewedAt:date.toISOString(),saved:true,note:'Existing note'}])]]);
globalThis.localStorage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
globalThis.window={dispatchEvent:()=>{}};
assert.equal(readCatalog()[0].observationStatus,'none');
updateDiscovery('earth',{observationStatus:'planned',observationDate:'2026-09-08'});
assert.equal(readCatalog()[0].note,'Existing note');
assert.equal(readCatalog()[0].saved,true);
updateDiscovery('earth',{observationStatus:'observed'});
assert.equal(readCatalog()[0].observationStatus,'observed');
discover('earth','Earth','Planet');
assert.equal(readCatalog().length,1);
console.log('PASS: northern/southern horizon geometry, overhead chart orientation, polar day, invalid inputs, independent NASA lunar phase, ordered events, and observation migration preserving notes/bookmarks.');
